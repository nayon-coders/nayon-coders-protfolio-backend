/**
 * @desc    Add milestone to timeline
 * @route   POST /api/admin/projects/:id/timeline
 * @access  Private
 */
exports.addMilestone = async (req, res, next) => {
  try {
    const { title, description, date, status } = req.body;
    
    if (!title) {
      return res.status(400).json({ success: false, message: 'Milestone title is required' });
    }

    const docRef = db.collection('projects').doc(req.params.id);
    const doc = await docRef.get();
    
    if (!doc.exists) {
      return res.status(404).json({ success: false, message: 'Project not found' });
    }

    const timeline = doc.data().timeline || [];
    
    const newMilestone = {
      id: uuidv4(),
      title,
      description: description || '',
      date: date || new Date().toISOString().split('T')[0],
      status: status || 'planned',
      order: timeline.length
    };

    timeline.push(newMilestone);

    await docRef.set({ timeline, updatedAt: new Date().toISOString() }, { merge: true });

    res.status(201).json({ success: true, message: 'Milestone added', data: newMilestone });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Update milestone in timeline
 * @route   PUT /api/admin/projects/:id/timeline/:milestoneId
 * @access  Private
 */
exports.updateMilestone = async (req, res, next) => {
  try {
    const { milestoneId } = req.params;
    const updateData = req.body;
    
    const docRef = db.collection('projects').doc(req.params.id);
    const doc = await docRef.get();
    
    if (!doc.exists) {
      return res.status(404).json({ success: false, message: 'Project not found' });
    }

    const timeline = doc.data().timeline || [];
    const index = timeline.findIndex(m => m.id === milestoneId);
    
    if (index === -1) {
      return res.status(404).json({ success: false, message: 'Milestone not found' });
    }

    timeline[index] = { ...timeline[index], ...updateData };

    await docRef.set({ timeline, updatedAt: new Date().toISOString() }, { merge: true });

    res.status(200).json({ success: true, message: 'Milestone updated', data: timeline[index] });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Delete milestone from timeline
 * @route   DELETE /api/admin/projects/:id/timeline/:milestoneId
 * @access  Private
 */
exports.deleteMilestone = async (req, res, next) => {
  try {
    const { milestoneId } = req.params;
    
    const docRef = db.collection('projects').doc(req.params.id);
    const doc = await docRef.get();
    
    if (!doc.exists) {
      return res.status(404).json({ success: false, message: 'Project not found' });
    }

    let timeline = doc.data().timeline || [];
    const index = timeline.findIndex(m => m.id === milestoneId);
    
    if (index === -1) {
      return res.status(404).json({ success: false, message: 'Milestone not found' });
    }

    timeline.splice(index, 1);
    
    // Reorder remaining items
    timeline = timeline.map((m, i) => ({ ...m, order: i }));

    await docRef.set({ timeline, updatedAt: new Date().toISOString() }, { merge: true });

    res.status(200).json({ success: true, message: 'Milestone deleted' });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Reorder timeline milestones
 * @route   PUT /api/admin/projects/:id/timeline/reorder
 * @access  Private
 */
exports.reorderTimeline = async (req, res, next) => {
  try {
    // Array of milestone IDs in the new order
    const { orderIds } = req.body;
    
    if (!orderIds || !Array.isArray(orderIds)) {
      return res.status(400).json({ success: false, message: 'Invalid order data' });
    }

    const docRef = db.collection('projects').doc(req.params.id);
    const doc = await docRef.get();
    
    if (!doc.exists) {
      return res.status(404).json({ success: false, message: 'Project not found' });
    }

    const timeline = doc.data().timeline || [];
    
    // Map to a new array using the provided IDs to maintain all data
    const newTimeline = [];
    orderIds.forEach((id, index) => {
      const milestone = timeline.find(m => m.id === id);
      if (milestone) {
        newTimeline.push({ ...milestone, order: index });
      }
    });

    await docRef.set({ timeline: newTimeline, updatedAt: new Date().toISOString() }, { merge: true });

    res.status(200).json({ success: true, message: 'Timeline reordered', data: newTimeline });
  } catch (error) {
    next(error);
  }
};
