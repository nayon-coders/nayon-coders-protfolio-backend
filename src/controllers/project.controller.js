const { db } = require('../config/firebase');
const { uploadFileLocally, deleteFileLocally, deleteFolderLocally } = require('../utils/fileUpload');
const { v4: uuidv4 } = require('uuid');

/**
 * @desc    Get all active/published projects for public view
 * @route   GET /api/projects
 * @access  Public
 */
exports.getPublicProjects = async (req, res, next) => {
  try {
    const snapshot = await db.collection('projects')
      .where('status', 'in', ['published', 'completed'])
      .orderBy('createdAt', 'desc')
      .get();
      
    // Fetch all active skills for population
    const skillsSnapshot = await db.collection('skills').where('active', '==', true).get();
    const skillsMap = {};
    skillsSnapshot.forEach(doc => {
      skillsMap[doc.id] = { id: doc.id, ...doc.data() };
    });

    const projects = [];
    snapshot.forEach(doc => {
      const data = doc.data();
      if (data.technologies && Array.isArray(data.technologies)) {
        data.technologies = data.technologies.map(skillId => skillsMap[skillId] || skillId);
      }
      projects.push({ id: doc.id, ...data });
    });

    res.status(200).json({ success: true, data: projects });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Get single project by slug
 * @route   GET /api/projects/:slug
 * @access  Public
 */
exports.getProjectBySlug = async (req, res, next) => {
  try {
    const { slug } = req.params;
    let snapshot = await db.collection('projects')
      .where('slug', '==', slug)
      .where('status', 'in', ['published', 'completed'])
      .limit(1)
      .get();

    let doc;
    if (snapshot.empty) {
      // Fallback: check if the 'slug' is actually a document ID
      const docById = await db.collection('projects').doc(slug).get();
      if (!docById.exists || !['published', 'completed'].includes(docById.data().status)) {
        return res.status(404).json({ success: false, message: 'Project not found' });
      }
      doc = docById;
    } else {
      doc = snapshot.docs[0];
    }

    const data = doc.data();

    // Populate technologies
    if (data.technologies && Array.isArray(data.technologies) && data.technologies.length > 0) {
      const skillsSnapshot = await db.collection('skills').where('active', '==', true).get();
      const skillsMap = {};
      skillsSnapshot.forEach(sDoc => {
        skillsMap[sDoc.id] = { id: sDoc.id, ...sDoc.data() };
      });
      data.technologies = data.technologies.map(skillId => skillsMap[skillId] || skillId);
    }

    res.status(200).json({ success: true, data: { id: doc.id, ...data } });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Create or Update a project (Admin)
 * @route   POST /api/admin/projects
 * @access  Private
 */
exports.createProject = async (req, res, next) => {
  try {
    // Expected to receive an 'id' generated by the frontend, to map media correctly
    const { id, ...projectData } = req.body;
    
    if (!id) {
      return res.status(400).json({ success: false, message: 'Project ID is required' });
    }

    const dataToSave = {
      ...projectData,
      updatedAt: new Date().toISOString()
    };

    // If it doesn't exist, we add createdAt
    const docRef = db.collection('projects').doc(id);
    const doc = await docRef.get();
    
    if (!doc.exists) {
      dataToSave.createdAt = new Date().toISOString();
    }

    await docRef.set(dataToSave, { merge: true });

    res.status(200).json({
      success: true,
      message: 'Project saved successfully',
      data: { id, ...dataToSave }
    });
  } catch (error) {
    next(error);
  }
};

