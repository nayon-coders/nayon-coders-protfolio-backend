/**
 * @desc    Upload project image
 * @route   POST /api/admin/projects/:id/images
 * @access  Private
 */
exports.uploadProjectImage = async (req, res, next) => {
  try {
    if (!req.file) {
      return res.status(400).json({ success: false, message: 'No image file provided' });
    }

    const { id } = req.params;
    const type = req.body.type || 'gallery'; // 'thumbnail' or 'gallery'
    
    const extension = req.file.originalname.split('.').pop();
    const fileName = `projects/${id}/${type}_${Date.now()}.${extension}`;
    
    // Upload locally
    const publicUrl = await uploadFileLocally(req.file.buffer, fileName, req);

    res.status(200).json({
      success: true,
      message: 'Image uploaded successfully',
      data: { url: publicUrl, type }
    });
  } catch (error) {
    next(error);
  }
};

